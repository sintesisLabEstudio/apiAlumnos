USE baseDatosAlumnos;
GO

-- Tabla ALUMNOS
CREATE TABLE [ALUMNOS] (
	[COD_ALUMNO] int NOT NULL,
	[NOMBRES] nvarchar(50) NULL,
	[APELLIDOS] nvarchar(50) NULL,
	CONSTRAINT [PK_ALUMNOS] PRIMARY KEY ([COD_ALUMNO])
);
GO

-- Tabla ASIGNATURAS
CREATE TABLE [ASIGNATURAS] (
	[ID_ASIGNATURA] int NOT NULL IDENTITY(1,1),
	[NOM_ASIGNATURA] nvarchar(50) NULL,
	CONSTRAINT [PK_ASIGNATURAS] PRIMARY KEY ([ID_ASIGNATURA])
);
GO

-- Tabla NOTAS
CREATE TABLE [NOTAS] (
	[ID_NOTA] int NOT NULL IDENTITY(1,1),
	[NOTA] decimal(2,1) NULL,
	[N_NOTA] int NULL,
	[COD_ALUMNO] int NOT NULL,
	[ID_ASIGNATURA] int NOT NULL,
	CONSTRAINT [PK_NOTAS] PRIMARY KEY ([ID_NOTA]),
	CONSTRAINT [FK_NOTAS_ALUMNOS_COD_ALUMNO] FOREIGN KEY ([COD_ALUMNO]) 
		REFERENCES [ALUMNOS] ([COD_ALUMNO]) ON DELETE CASCADE,
	CONSTRAINT [FK_NOTAS_ASIGNATURAS_ID_ASIGNATURA] FOREIGN KEY ([ID_ASIGNATURA]) 
		REFERENCES [ASIGNATURAS] ([ID_ASIGNATURA]) ON DELETE CASCADE
);
GO

-- Crear índices
CREATE INDEX [IX_NOTAS_COD_ALUMNO] ON [NOTAS] ([COD_ALUMNO]);
CREATE INDEX [IX_NOTAS_ID_ASIGNATURA] ON [NOTAS] ([ID_ASIGNATURA]);
GO

PRINT 'Base de datos y tablas creadas exitosamente';
